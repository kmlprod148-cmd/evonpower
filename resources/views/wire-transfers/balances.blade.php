<script>
document.addEventListener('DOMContentLoaded', function() {
    const roleFilter = document.getElementById('roleFilter');
    const balanceFilter = document.getElementById('balanceFilter');
    const rows = document.querySelectorAll('.user-row');

    function filterRows() {
        const selectedRole = roleFilter.value;
        const selectedBalance = balanceFilter.value;

        rows.forEach(row => {
            const role = row.dataset.role;
            const balance = parseFloat(row.dataset.balance);

            let showRow = true;

            // Filtre par rôle
            if (selectedRole && role !== selectedRole) {
                showRow = false;
            }

            // Filtre par solde
            if (selectedBalance) {
                switch (selectedBalance) {
                    case 'positive':
                        if (balance <= 0) showRow = false;
                        break;
                    case 'zero':
                        if (balance !== 0) showRow = false;
                        break;
                    case 'negative':
                        if (balance >= 0) showRow = false;
                        break;
                }
            }

            row.style.display = showRow ? '' : 'none';
        });
    }

    roleFilter.addEventListener('change', filterRows);
    balanceFilter.addEventListener('change', filterRows);
});
</script>
